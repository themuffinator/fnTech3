"""Export the imagegen icon masters and package them for every platform.

Writes, for each game icon (all committed; see assets/icons/games/README.md):
  assets/icons/games/<key>/<key>-<size>.png        16-512 px (freedesktop sizes)
  assets/icons/games/<key>/<key>.ico               Windows, PNG frames 16-256 px
  assets/icons/games/<key>/<key>.icns              macOS, 16-1024 px incl. Retina
  assets/icons/games/<key>/fntech3-<key>.desktop   Linux launcher (engine profiles only)
and once:
  assets/icons/games/preview.png                   overview for documentation
  code/platform/game_icon_table.h                  profile key -> resource id
  code/platform/game_icon_data.cpp                 frames linked into non-Windows clients
  code/win32/win_game_icons.rc                     icon resources for Windows clients

Run from any directory: python scripts/generate_game_icons.py [key ...]
Development-only dependency: Pillow. Builds use the
committed outputs and never run this script.
"""
from __future__ import annotations

import argparse
import io
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))

ICON_ROOT = ROOT / "assets" / "icons" / "games"
TABLE = ROOT / "code" / "platform" / "game_icon_table.h"
DATA = ROOT / "code" / "platform" / "game_icon_data.cpp"
RESOURCES = ROOT / "code" / "win32" / "win_game_icons.rc"

# Standalone PNGs cover the freedesktop hicolor sizes and the embedded frames.
# The 20/40 px Windows frames live only in the ICO and the 1024 px frame only in
# the ICNS; assets/icons/games/sources retains the imagegen masters.
PNG_SIZES = (16, 22, 24, 32, 48, 64, 96, 128, 256, 512)
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 96, 128, 256)
ICNS_ENTRIES = (("icp4", 16), ("icp5", 32), ("icp6", 64), ("ic07", 128), ("ic08", 256),
                ("ic09", 512), ("ic10", 1024), ("ic11", 32), ("ic12", 64), ("ic13", 256),
                ("ic14", 512))
RENDER_SIZES = tuple(sorted(set(PNG_SIZES) | set(ICO_SIZES) | {size for _, size in ICNS_ENTRIES}))
EMBED_SIZES = (16, 32, 64, 128)
HEADER = "Generated by scripts/generate_game_icons.py. Do not edit."


def encode_png(image) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, "PNG", optimize=True)
    return buffer.getvalue()


def build_ico(frames: dict[int, bytes]) -> bytes:
    """ICO with PNG-compressed frames (supported by Windows Vista and later)."""
    sizes = [s for s in ICO_SIZES]
    out = bytearray(struct.pack("<HHH", 0, 1, len(sizes)))
    offset = 6 + 16 * len(sizes)
    for size in sizes:
        dim = 0 if size >= 256 else size
        out += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(frames[size]), offset)
        offset += len(frames[size])
    for size in sizes:
        out += frames[size]
    return bytes(out)


def build_icns(frames: dict[int, bytes]) -> bytes:
    body = bytearray()
    for kind, size in ICNS_ENTRIES:
        body += kind.encode("ascii") + struct.pack(">I", 8 + len(frames[size])) + frames[size]
    return b"icns" + struct.pack(">I", 8 + len(body)) + bytes(body)


def desktop_entry(icon) -> str:
    return "\n".join([
        "[Desktop Entry]",
        "Type=Application",
        f"Name={icon.name}",
        "GenericName=fnTech3 game profile",
        f"Comment=Play {icon.name} with fnTech3",
        f"Exec=fntech3 +set com_gameProfile {icon.key}",
        f"Icon=fntech3-{icon.key}",
        "Terminal=false",
        "Categories=Game;ActionGame;",
        f"StartupWMClass=fntech3-{icon.key}",
        "",
    ])


def c_bytes(data: bytes, width: int = 100) -> str:
    lines, line = [], ""
    for value in data:
        item = f"{value},"
        if len(line) + len(item) > width:
            lines.append(line)
            line = ""
        line += item
    if line:
        lines.append(line)
    return "\n".join(lines)


def write_if_changed(path: Path, data: bytes, text_file: bool = False) -> bool:
    if path.exists():
        current = path.read_bytes()
        # Checkouts may convert text to CRLF; that is not a change.
        if (current.replace(b"\r\n", b"\n") if text_file else current) == data:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def text(content: str) -> bytes:
    return content.encode("utf-8")


def generate_sources(icons, frames_by_key) -> None:
    table = [f"// {HEADER}", "#pragma once", "", "namespace fntech3::icon {",
             "// One row per profile key; `resource` is the RT_GROUP_ICON id linked",
             "// into Windows clients by code/win32/win_client_resource.rc.",
             "struct BuiltinIcon {", "    const char *profile;", "    unsigned resource;", "};", "",
             "inline constexpr BuiltinIcon kBuiltinIcons[] = {"]
    for icon in icons:
        table.append(f'    {{"{icon.key}", {icon.resource}}},')
    table += ["};", "", "// Frames compiled into clients without Windows icon resources.",
              "inline constexpr unsigned kEmbeddedIconSizes[] = {"
              + ", ".join(str(s) for s in EMBED_SIZES) + "};",
              "} // namespace fntech3::icon", ""]
    write_if_changed(TABLE, text("\n".join(table)), True)

    data = [f"// {HEADER}",
            "// PNG frames of the game icon remakes for clients that have no Windows",
            "// resources to read them from. Artwork: assets/icons/games.",
            '#include "game_icon_builtin.hpp"', "", "namespace fntech3::icon {", "namespace {"]
    rows = []
    for icon in icons:
        for size in EMBED_SIZES:
            name = f"k{icon.symbol}{size}"
            blob = frames_by_key[icon.key][size]
            data.append(f"const unsigned char {name}[{len(blob)}] = {{")
            data.append(c_bytes(blob))
            data.append("};")
            rows.append(f'    {{"{icon.key}", {size}, {name}, sizeof({name})}},')
    data += ["", "const EncodedImage kImages[] = {", *rows, "};", "} // namespace", "",
             "const EncodedImage *EmbeddedImages(size_t &count)", "{",
             "    count = sizeof(kImages) / sizeof(kImages[0]);", "    return kImages;", "}",
             "} // namespace fntech3::icon", ""]
    write_if_changed(DATA, text("\n".join(data)), True)

    rc = [f"// {HEADER}",
          "// Included by win_client_resource.rc; ids match code/platform/game_icon_table.h.",
          "#ifndef __MINGW32__"]
    for icon in icons:
        rc.append(f'{icon.resource} ICON DISCARDABLE "../../assets/icons/games/{icon.key}/{icon.key}.ico"')
    rc.append("#else")
    for icon in icons:
        rc.append(f'{icon.resource} ICON DISCARDABLE "assets/icons/games/{icon.key}/{icon.key}.ico"')
    rc += ["#endif", ""]
    write_if_changed(RESOURCES, text("\n".join(rc)), True)


def preview(images_by_key, keys) -> bytes:
    from PIL import Image, ImageDraw

    cell = 160
    row_height = 176
    columns = min(8, (len(keys) + 1) // 2)
    rows = (len(keys) + columns - 1) // columns
    sheet = Image.new("RGBA", (columns * cell, rows * row_height), (35, 38, 44, 255))
    draw = ImageDraw.Draw(sheet)
    for index, key in enumerate(keys):
        x = (index % columns) * cell + 16
        y = (index // columns) * row_height + 12
        sheet.alpha_composite(images_by_key[key][128], (x, y))
        draw.text((x + 64, y + 138), key, fill=(225, 228, 235), anchor="mt")
    return encode_png(sheet)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("keys", nargs="*", help="icon keys to re-export (default: all)")
    args = parser.parse_args(argv)

    import game_icons

    profiles = game_icons.ordered()
    icons = profiles + game_icons.standalone()
    selected = set(args.keys or [icon.key for icon in icons])
    unknown = selected - {icon.key for icon in icons}
    if unknown:
        parser.error(f"unknown icon keys: {', '.join(sorted(unknown))}")

    frames_by_key: dict[str, dict[int, bytes]] = {}
    images_by_key = {}
    from PIL import Image

    for icon in icons:
        folder = ICON_ROOT / icon.key
        if icon.key in selected:
            frames = {size: encode_png(game_icons.render(icon.key, size)) for size in RENDER_SIZES}
            changed = 0
            for size in PNG_SIZES:
                changed += write_if_changed(folder / f"{icon.key}-{size}.png", frames[size])
            changed += write_if_changed(folder / f"{icon.key}.ico", build_ico(frames))
            changed += write_if_changed(folder / f"{icon.key}.icns", build_icns(frames))
            if icon.resource is not None:
                changed += write_if_changed(folder / f"fntech3-{icon.key}.desktop", text(desktop_entry(icon)), True)
            for stale in folder.glob(f"{icon.key}-*.png"):
                size = stale.stem.rsplit("-", 1)[1]
                if not size.isdigit() or int(size) not in PNG_SIZES:
                    stale.unlink()
            print(f"{icon.key}: {changed} file(s) updated")
        else:
            frames = {size: (folder / f"{icon.key}-{size}.png").read_bytes() for size in PNG_SIZES}
        frames_by_key[icon.key] = frames
        images_by_key[icon.key] = {128: Image.open(io.BytesIO(frames[128])).convert("RGBA")}

    write_if_changed(ICON_ROOT / "preview.png", preview(images_by_key, [i.key for i in icons]))
    generate_sources(profiles, frames_by_key)
    print(f"Wrote {len(icons)} game icons under {ICON_ROOT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
