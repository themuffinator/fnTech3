#!/usr/bin/env python3
"""Capture bounded Academy demos and replay them with the pinned OpenJK client.

The native fnTech3 server writer is tested separately from an OpenJK client
writer control. This is maintained-reader subset evidence, not retail-engine
playback or fnTech3 client playback. All processes use stable binaries, private
unswitched desktops, windowed rendering and disabled input. No input is injected.
"""
from pathlib import Path
import argparse
import datetime
import json
import os
import re
import stat
import subprocess
import time
import zipfile

import probe_jka_openjk_peer as peer
from jka_demo_evidence import generated_demo

ROOT = peer.ROOT
CONFIG = 'jka-demo-probe.cfg'
DEMO_FAILURE = re.compile(r'Demo file was truncated|demoMsglen|couldn.t open.*(?:demo|dm_26)', re.I)


def markers(origin):
    if origin not in ('server', 'client'):
        raise ValueError('Select one of the generated demo origins')
    return ('FNTECH3_JKA_DEMO_ACTIVE_' + origin.upper(),
            'FNTECH3_JKA_DEMO_EOF_' + origin.upper())


def configuration(origin):
    active, completed = markers(origin)
    return (peer.configuration('openjk', 1)
        + 'set developer "0"\n'
        + 'set timedemo "0"\n'
        + f'set activeAction "echo {active}; wait 5; screenshot_png jka-demo-{origin};"\n'
        + f'set nextdemo "echo {completed}; quit;"\n')


def launch_command(executable, installation, home, origin):
    markers(origin)
    settings = dict(fs_basepath=installation, fs_homepath=home, fs_game='', fs_cdpath='',
        r_fullscreen=0, r_mode=-1, r_customWidth=800, r_customHeight=600,
        in_mouse=0, in_keyboard=0, in_joystick=0, in_nograb=1, s_initsound=0,
        developer=0, logfile=2, net_enabled=0, net_ip='127.0.0.1', net_port=0,
        com_unpackLibraries=1, cl_renderer='rd-vanilla', com_introplayed=1, com_bootlogo=0)
    result = peer.command(executable, settings,
        ['+exec', CONFIG, '+demo', f'jka-bounded-{origin}.dm_26'])
    if (sum(word.startswith('+') for word in result) > 32
            or len(subprocess.list2cmdline(result[1:]).encode('utf-8')) >= 1024):
        raise ValueError('Startup arguments exceed engine limits; shorten the output path')
    return result


def playback_evidence(text, origin):
    active, completed = markers(origin)
    trace = re.sub(r'^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} ', '', text, flags=re.M)
    result = peer.connection_evidence('', '', text)
    result['activeActionObserved'] = bool(re.search('^' + active + r'\s*$', trace, re.M))
    result['demoCompletedObserved'] = bool(re.search('^' + completed + r'\s*$', trace, re.M))
    result['clientFrontiers'] += [line for line in text.splitlines() if DEMO_FAILURE.search(line)]
    result['legacyModulesLoaded'] = {name: bool(re.search(r'VM_CreateLegacy: ' + name + r'\.dll succeeded', text))
        for name in ('uix86', 'cgamex86')}
    return result


def replay(args, origin, source, capture_output, output, executable, installation, renderer):
    # Only the demos just generated by the strict capture pair may be selected.
    raw, details = generated_demo(source, capture_output)
    home = output / 'home'
    game = home / 'base'
    launch = launch_command(executable, installation, home, origin)
    output.mkdir(parents=True)
    (game / 'demos').mkdir(parents=True)
    demo = game / 'demos' / f'jka-bounded-{origin}.dm_26'
    demo.write_bytes(raw)
    for name in ('jampconfig.cfg', 'jampconfig_server.cfg'):
        (game / name).write_text('', encoding='ascii')
    config = configuration(origin)
    (game / CONFIG).write_text(config, encoding='ascii')
    (output / CONFIG).write_text(config, encoding='ascii')
    binaries = (executable, renderer, executable.parent / 'SDL2.dll')
    identities = {str(path): peer.sha(path) for path in binaries}
    before = peer.inventory(installation)
    candidates = peer.modules(installation)
    report = dict(origin=origin, command=launch, generatedDemo=details,
        writer='fnTech3 native server' if origin == 'server' else 'OpenJK client control',
        reader='pinned OpenJK client', binarySha256=identities,
        moduleCandidates=candidates,
        scope='Maintained-reader playback subset; fnTech3-client and retail-engine demo gates remain open',
        desktopSwitched=False, inputInjected=False, screenshots=[], passed=False, visualPassed=None)
    process, stopped = None, False
    begin = time.monotonic()
    try:
        process = peer.launch_private(launch, executable, home, output / 'stdout.log')
        report['desktop'] = process.name
        deadline = time.monotonic() + args.timeout
        while process.poll() is None and time.monotonic() < deadline:
            text = peer.read(game / 'qconsole.log') + '\n' + peer.read(output / 'stdout.log')
            failure = next((line for line in text.splitlines()
                if peer.ERRORS.search(line) or DEMO_FAILURE.search(line)), None)
            if failure:
                report['earlyStopReason'] = failure
                break
            time.sleep(.2)
        report['exitCode'] = process.poll()
        report['forcedStop'] = report['exitCode'] is None
    except (OSError, RuntimeError, subprocess.TimeoutExpired) as error:
        report['error'] = f'{type(error).__name__}: {error}'
    finally:
        if process:
            try:
                process.close()
                stopped = True
            except (OSError, subprocess.TimeoutExpired) as error:
                report['stopError'] = str(error)
        text = peer.read(game / 'qconsole.log') + '\n' + peer.read(output / 'stdout.log')
        (output / 'console.log').write_text(text, encoding='utf-8')
        report.update(playback_evidence(text, origin))
        report['snapshotRecordsComplete'] = (report['validSnapshotCount'] == details['recordCount'] - 1
            and max((row['sequence'] for row in report['snapshots']), default=-1) == details['lastSequence'])
        if (report['snapshotRecordsComplete'] and report['activeActionObserved']
                and not report['demoCompletedObserved'] and 'execing mpdefault.cfg' in text):
            report['readerCompletionFrontier'] = ('Pinned OpenJK ordinary active-demo completion throws '
                'ERR_DISCONNECT before nextdemo; full snapshot records and UI restart observed, normal quit absent')
        report['moduleDiagnostics'] = [line for line in text.splitlines()
            if re.search(r'VM_LoadDll|native module|VM_CreateLegacy: (?:ui|cgame)x86\.dll', line, re.I)]
        report['nativeCaches'] = [dict(path=str(path.relative_to(home)), sha256=peer.sha(path))
            for path in home.rglob('*') if path.is_file() and path.suffix.casefold() in ('.dll', '.tmp')]
        cached_hashes = {row['sha256'] for row in report['nativeCaches']}
        report['moduleCacheIdentitiesMatch'] = all(any(row['member'].casefold() == name + '.dll'
            and row['sha256'] in cached_hashes for row in candidates) for name in ('uix86', 'cgamex86'))
        if stopped:
            try:
                report['demoUnchanged'] = generated_demo(demo, home)[1] == details
                captures = list(home.rglob(f'jka-demo-{origin}.png'))
                if len(captures) != 1:
                    raise ValueError('Replay requires exactly one engine PNG at the expected name')
                current = captures[0]
                while True:
                    meta = current.lstat()
                    if not current.is_relative_to(home) or stat.S_ISLNK(meta.st_mode) or getattr(meta, 'st_file_attributes', 0) & 0x400:
                        raise ValueError('Engine PNG traverses a linked or foreign path')
                    if current == home:
                        break
                    current = current.parent
                if captures[0].stat().st_size > 16 * 1024 * 1024:
                    raise ValueError('Engine PNG exceeds capture bounds')
                with captures[0].open('rb') as image:
                    png = image.read(16 * 1024 * 1024 + 1)
                if not peer.valid_capture(png):
                    raise ValueError('Engine PNG has invalid dimensions, framing or pixels')
                target = output / captures[0].name
                target.write_bytes(png)
                report['screenshots'].append(peer.capture_identity(target))
            except (OSError, ValueError) as error:
                report['artifactError'] = str(error)
        report['installationUnchanged'] = before == peer.inventory(installation)
        report['binariesUnchanged'] = all(peer.sha(Path(path)) == digest for path, digest in identities.items())
        report['elapsedSeconds'] = round(time.monotonic() - begin, 3)
        report['passed'] = bool(stopped and report.get('exitCode') == 0 and not report.get('forcedStop')
            and not report.get('error') and not report.get('stopError') and not report.get('artifactError')
            and report['activeActionObserved'] and report['demoCompletedObserved']
            and report['validSnapshotCount'] >= 2 and report['deltaSnapshotObserved']
            and report['windowedObserved'] and not report['clientFrontiers']
            and all(report['legacyModulesLoaded'].values()) and report['moduleCacheIdentitiesMatch']
            and len(report['screenshots']) == 1 and report.get('demoUnchanged')
            and report['installationUnchanged'] and report['binariesUnchanged'])
        report['homeRemoved'] = False
        if stopped:
            try:
                peer.remove_home(home, output)
                report['homeRemoved'] = True
            except (OSError, RuntimeError, ValueError) as error:
                report['cleanupError'] = str(error)
                report['passed'] = False
        (output / 'result.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    return report


def run(args):
    # Validate before creating anything, including nested capture/replay homes.
    if args.timeout > 60:
        raise ValueError('Bounded demo probes allow at most 60 seconds per process stage')
    args.direction, args.server_only, args.record_demos = 'openjk-to-fntech3', False, True
    installation, output, server, client, renderer, _, _ = peer.validate(args)
    identities = {str(path): peer.sha(path) for path in (server, client, renderer, client.parent / 'SDL2.dll')}
    output.mkdir(parents=True)
    capture_args = argparse.Namespace(**vars(args))
    capture_args.output = output / 'capture'
    report = dict(utc=datetime.datetime.now(datetime.timezone.utc).isoformat(), profile='jka-mp',
        map=args.map, pure=args.pure, openjkReferenceCommit=peer.OPENJK_COMMIT,
        binarySha256=identities, installation=str(installation),
        scope='Native fnTech3 server demo -> maintained reader subset, with separate maintained-client writer control',
        retailEnginePlayback=False, fnTech3ClientPlayback=False, passed=False, playbacks=[])
    try:
        selected_capture = getattr(args, 'replay_capture', None)
        if selected_capture is None:
            report['capturePassed'] = peer.run(capture_args)
            capture = json.loads((capture_args.output / 'result.json').read_text(encoding='utf-8'))
        else:
            capture_args.output, capture = previous_capture(selected_capture, installation, identities, args.pure, args.map)
            report['capturePassed'] = True
            report['captureReused'] = True
        report['captureResult'] = str((capture_args.output / 'result.json').relative_to(ROOT))
        if report['capturePassed']:
            # A missing origin or a capture disagreement must not silently select
            # an arbitrary .dm_26 from a writable directory.
            records = {row['origin']: row for row in capture['demos']}
            if set(records) != {'server', 'client'} or len(capture['demos']) != 2:
                raise ValueError('Strict capture did not produce both bounded demo origins')
            for origin in ('server', 'client'):
                if any(peer.sha(Path(path)) != digest for path, digest in identities.items()):
                    raise ValueError('Stable capture binaries changed before replay')
                source = capture_args.output / 'demos' / f'{origin}.dm_26'
                if generated_demo(source, capture_args.output)[1]['sha256'] != records[origin]['sha256']:
                    raise ValueError('Captured demo identity changed before replay')
                report['playbacks'].append(replay(args, origin, source, capture_args.output,
                    output / f'replay-{origin}', client, installation, renderer))
        report['passed'] = bool(report['capturePassed'] and len(report['playbacks']) == 2
            and all(row['passed'] for row in report['playbacks']))
    except (OSError, ValueError, RuntimeError) as error:
        report['error'] = f'{type(error).__name__}: {error}'
    report['binariesUnchanged'] = all(peer.sha(Path(path)) == digest for path, digest in identities.items())
    report['passed'] = report['passed'] and report['binariesUnchanged']
    (output / 'result.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    summary = {key: report.get(key) for key in ('passed', 'capturePassed', 'captureReused', 'error')}
    summary['playbacks'] = [{key: row.get(key) for key in ('origin', 'passed', 'activeActionObserved',
        'demoCompletedObserved', 'snapshotRecordsComplete', 'validSnapshotCount', 'deltaSnapshotObserved',
        'forcedStop', 'homeRemoved', 'readerCompletionFrontier', 'artifactError', 'error', 'stopError')}
        for row in report['playbacks']]
    print(json.dumps(summary, indent=2))
    return report['passed']


def previous_capture(path, installation, identities, pure, mapname):
    """Accept only our finalized strict capture report, never an arbitrary demo."""
    path = Path(os.path.abspath(path))
    if not path.is_relative_to(ROOT / '.tmp') or path == ROOT / '.tmp':
        raise ValueError('Previous capture must stay below project .tmp')
    current = ROOT
    for name in path.relative_to(ROOT).parts:
        current /= name
        meta = current.lstat()
        if stat.S_ISLNK(meta.st_mode) or getattr(meta, 'st_file_attributes', 0) & 0x400 or not current.is_dir():
            raise ValueError('Previous capture traverses a linked or non-directory path')
    result = path / 'result.json'
    meta = result.lstat()
    if not stat.S_ISREG(meta.st_mode) or getattr(meta, 'st_file_attributes', 0) & 0x400 or meta.st_size > 1024 * 1024:
        raise ValueError('Previous capture needs a bounded regular report')
    with result.open('rb') as source:
        raw = source.read(1024 * 1024 + 1)
    if len(raw) > 1024 * 1024:
        raise ValueError('Previous capture report exceeds bounds')
    report = json.loads(raw)
    if not isinstance(report, dict):
        raise ValueError('Previous capture report is not a structured result')
    binaries = report.get('binarySha256')
    expected = {path for path in identities if Path(path).name.casefold() != 'sdl2.dll'}
    if (report.get('passed') is not True or report.get('recordingRequested') is not True or report.get('homesRemoved') is not True
            or report.get('installationUnchanged') is not True or report.get('binariesUnchanged') is not True
            or report.get('direction') != 'openjk-to-fntech3' or report.get('pure') != pure
            or report.get('profile') != 'jka-mp' or report.get('map') != mapname or report.get('installation') != str(installation)
            or report.get('openjkReferenceCommit') != peer.OPENJK_COMMIT
            or not isinstance(binaries, dict) or set(binaries) != expected
            or any(identities.get(path) != digest for path, digest in binaries.items())
            or not isinstance(report.get('demos'), list) or len(report['demos']) != 2
            or any(not isinstance(row, dict) or row.get('origin') not in ('server', 'client')
                or not isinstance(row.get('sha256'), str) for row in report['demos'])):
        raise ValueError('Previous capture lacks strict admission/cleanup or matching stable identities')
    return path, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, default=ROOT / 'meson/build/win32-dev/fntech3.exe')
    parser.add_argument('--server', type=Path, default=ROOT / 'meson/build/win32-dev/fntech3.ded.exe')
    parser.add_argument('--openjk-directory', type=Path, default=ROOT / '.tmp/runtime/jka-openjk-build')
    parser.add_argument('--installation', type=Path, default=Path('E:/Games/Jedi Academy'))
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--replay-capture', type=Path, help='Replay only a previous strict finalized capture with matching binaries and installation')
    parser.add_argument('--renderer', choices=('glx', 'vk', 'rtx'), default='glx')
    parser.add_argument('--map', default='mp/ffa1')
    parser.add_argument('--pure', action='store_true')
    parser.add_argument('--frames', type=int, default=180)
    parser.add_argument('--timeout', type=float, default=60)
    args = parser.parse_args()
    if os.name != 'nt':
        parser.error('Windows private-desktop harness required')
    try:
        return 0 if run(args) else 1
    except (OSError, ValueError, zipfile.BadZipFile) as error:
        parser.error(str(error))


if __name__ == '__main__':
    raise SystemExit(main())
