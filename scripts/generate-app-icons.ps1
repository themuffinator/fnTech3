# Export the approved raster artwork; requires Windows PowerShell/.NET drawing.
# No drawing or retouching is performed. Run from any directory.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$projectRoot = Split-Path $PSScriptRoot -Parent
$iconRoot = Join-Path $projectRoot 'assets/icons'
$source = [System.Drawing.Image]::FromFile((Join-Path $iconRoot 'fntech3-icon-source.png'))
$sizes = @(16, 24, 32, 48, 64, 128, 256, 512, 1024)
$frames = @{}
try {
    foreach ($size in $sizes) {
        $bitmap = New-Object System.Drawing.Bitmap($size, $size)
        $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
        try {
            $graphics.CompositingMode = [System.Drawing.Drawing2D.CompositingMode]::SourceCopy
            $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
            $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
            $graphics.DrawImage($source, 0, 0, $size, $size)
            $destination = Join-Path $iconRoot "fntech3-$size.png"
            $bitmap.Save($destination, [System.Drawing.Imaging.ImageFormat]::Png)
            $frames[$size] = [System.IO.File]::ReadAllBytes($destination)
            if ($size -eq 128) {
                $header = New-Object System.Text.StringBuilder
                [void]$header.AppendLine('// Generated by scripts/generate-app-icons.ps1. Do not edit.')
                [void]$header.AppendLine('#pragma once')
                [void]$header.AppendLine('static const unsigned int FNTECH3_ICON_SIZE = 128;')
                [void]$header.AppendLine('static const unsigned char FNTECH3_ICON_RGBA[128 * 128 * 4 + 1] =')
                for ($y = 0; $y -lt $size; $y++) {
                    [void]$header.Append('"')
                    for ($x = 0; $x -lt $size; $x++) {
                        $pixel = $bitmap.GetPixel($x, $y)
                        foreach ($value in @($pixel.R, $pixel.G, $pixel.B, $pixel.A)) {
                            [void]$header.Append('\').Append([Convert]::ToString($value, 8).PadLeft(3, '0'))
                        }
                    }
                    [void]$header.AppendLine('"')
                }
                [void]$header.AppendLine(';')
                [System.IO.File]::WriteAllText((Join-Path $projectRoot 'code/platform/application_icon_data.h'), $header.ToString(), [System.Text.UTF8Encoding]::new($false))
            }
        } finally { $graphics.Dispose(); $bitmap.Dispose() }
    }
} finally { $source.Dispose() }

# PNG-compressed ICO entries preserve full alpha, including the 256px frame.
$icoSizes = @($sizes | Where-Object { $_ -le 256 })
$stream = [System.IO.File]::Create((Join-Path $iconRoot 'fntech3.ico'))
$writer = [System.IO.BinaryWriter]::new($stream)
try {
    $writer.Write([uint16]0); $writer.Write([uint16]1); $writer.Write([uint16]$icoSizes.Count)
    $offset = 6 + 16 * $icoSizes.Count
    foreach ($size in $icoSizes) {
        $dimension = if ($size -eq 256) { 0 } else { $size }
        $writer.Write([byte]$dimension); $writer.Write([byte]$dimension)
        $writer.Write([byte]0); $writer.Write([byte]0)
        $writer.Write([uint16]1); $writer.Write([uint16]32)
        $writer.Write([uint32]$frames[$size].Length); $writer.Write([uint32]$offset)
        $offset += $frames[$size].Length
    }
    foreach ($size in $icoSizes) { $writer.Write([byte[]]$frames[$size]) }
} finally { $writer.Dispose() }

# Standard ICNS PNG representations, including Retina sizes.
$entries = [ordered]@{ icp4=16; icp5=32; icp6=64; ic07=128; ic08=256; ic09=512; ic10=1024; ic11=32; ic12=64; ic13=256; ic14=512 }
function Write-BigEndian32($writer, [uint32]$value) {
    $bytes = [BitConverter]::GetBytes($value)
    if ([BitConverter]::IsLittleEndian) { [Array]::Reverse($bytes) }
    $writer.Write($bytes)
}
$length = 8
foreach ($size in $entries.Values) { $length += 8 + $frames[$size].Length }
$stream = [System.IO.File]::Create((Join-Path $iconRoot 'fntech3.icns'))
$writer = [System.IO.BinaryWriter]::new($stream)
try {
    $writer.Write([System.Text.Encoding]::ASCII.GetBytes('icns'))
    Write-BigEndian32 $writer $length
    foreach ($entry in $entries.GetEnumerator()) {
        $writer.Write([System.Text.Encoding]::ASCII.GetBytes($entry.Key))
        Write-BigEndian32 $writer (8 + $frames[$entry.Value].Length)
        $writer.Write([byte[]]$frames[$entry.Value])
    }
} finally { $writer.Dispose() }
Write-Output "Exported application icons to $iconRoot"
