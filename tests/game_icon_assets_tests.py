"""Validate the game icon remakes and every platform container built from them.

Stdlib only: the generator (scripts/generate_game_icons.py) needs Pillow,
but its committed outputs must stay checkable without it.
"""
import re
import struct
import unittest
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GAMES = ROOT / "assets" / "icons" / "games"
TABLE = ROOT / "code" / "platform" / "game_icon_table.h"
DATA = ROOT / "code" / "platform" / "game_icon_data.cpp"
RESOURCES = ROOT / "code" / "win32" / "win_game_icons.rc"
GENERATED = "Generated by scripts/generate_game_icons.py. Do not edit."

PNG_SIZES = (16, 22, 24, 32, 48, 64, 96, 128, 256, 512)
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 96, 128, 256)
ICNS_SIZES = {b"icp4": 16, b"icp5": 32, b"icp6": 64, b"ic07": 128, b"ic08": 256, b"ic09": 512,
              b"ic10": 1024, b"ic11": 32, b"ic12": 64, b"ic13": 256, b"ic14": 512}
EMBEDDED_SIZES = (16, 32, 64, 128)


def table_rows():
    rows = re.findall(r'\{"([a-z0-9-]+)", (\d+)\},', TABLE.read_text(encoding="utf-8"))
    return [(key, int(resource)) for key, resource in rows]


def decode_png(test, data, size, pixels=None):
    """Check structure and CRCs; unfilter small frames and return (min, max) alpha."""
    if pixels is None:
        pixels = size <= 128  # pure-Python unfiltering of larger frames is slow
    test.assertEqual(data[:8], b"\x89PNG\r\n\x1a\n")
    position = 8
    compressed = bytearray()
    kinds = []
    while position < len(data):
        length, kind = struct.unpack_from(">I4s", data, position)
        payload = data[position + 8:position + 8 + length]
        crc, = struct.unpack_from(">I", data, position + 8 + length)
        test.assertEqual(zlib.crc32(kind + payload), crc)
        kinds.append(kind)
        if kind == b"IHDR":
            width, height, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", payload)
            test.assertEqual((width, height, depth, colour, interlace), (size, size, 8, 6, 0))
        elif kind == b"IDAT":
            compressed.extend(payload)
        position += length + 12
    test.assertEqual(position, len(data))
    # The engine's decoder expects IDAT straight after IHDR and IEND last.
    test.assertEqual((kinds[0], kinds[1], kinds[-1]), (b"IHDR", b"IDAT", b"IEND"))
    raw = zlib.decompress(bytes(compressed))
    stride = size * 4
    test.assertEqual(len(raw), size * (stride + 1))
    test.assertTrue(all(raw[y * (stride + 1)] <= 4 for y in range(size)))
    if not pixels:
        return None
    alphas = []
    previous = bytearray(stride)
    for y in range(size):
        line = raw[y * (stride + 1):(y + 1) * (stride + 1)]
        kind, row = line[0], bytearray(line[1:])
        test.assertLessEqual(kind, 4)
        for x in range(stride):
            a = row[x - 4] if x >= 4 else 0
            b = previous[x]
            c = previous[x - 4] if x >= 4 else 0
            if kind == 1:
                row[x] = (row[x] + a) & 0xFF
            elif kind == 2:
                row[x] = (row[x] + b) & 0xFF
            elif kind == 3:
                row[x] = (row[x] + (a + b) // 2) & 0xFF
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                row[x] = (row[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 0xFF
        alphas.extend(row[3::4])
        previous = row
    return min(alphas), max(alphas)


class GameIconAssetsTests(unittest.TestCase):
    def test_every_profile_has_a_remake_in_catalogue_order(self):
        source = (ROOT / "code" / "qcommon" / "game_profile.cpp").read_text(encoding="utf-8")
        profiles = re.findall(r"^\tCOM_GAME_[A-Z0-9_]+,\s*\n\t\"([a-z0-9-]+)\",", source, re.M)
        self.assertGreaterEqual(len(profiles), 13)
        keys = [key for key, _ in table_rows()]
        self.assertEqual(len(keys), len(set(keys)))
        for profile in profiles:
            self.assertIn(profile, keys)
        resources = [resource for _, resource in table_rows()]
        self.assertEqual(resources, list(range(101, 101 + len(resources))))
        meson = (ROOT / "meson.build").read_text(encoding="utf-8")
        listed = re.search(r"game_icon_keys = \[([^\]]*)\]", meson)
        self.assertIsNotNone(listed)
        self.assertEqual(re.findall(r"'([a-z0-9-]+)'", listed.group(1)), keys)

    def test_png_sets_have_valid_artwork_alpha(self):
        for key, _ in table_rows():
            for size in PNG_SIZES:
                with self.subTest(key=key, size=size):
                    alpha = decode_png(self, (GAMES / key / f"{key}-{size}.png").read_bytes(), size)
                    if alpha is not None:
                        # Thin strokes/subpixel margins are antialiased in the
                        # smallest exports; square backgrounds can be opaque.
                        self.assertGreaterEqual(alpha[1], 224)
                        if key == "stvef-mp" and size == 16:
                            # A rounded tile's corner cutout is subpixel at
                            # caption size; coverage remains partly visible.
                            self.assertLessEqual(alpha[0], 64)
                        else:
                            self.assertTrue(alpha[0] <= 32 or alpha[0] == 255)
            # 20/40 px live only in the ICO and 1024 px only in the ICNS.
            self.assertEqual(sorted(int(p.stem.rsplit("-", 1)[1]) for p in (GAMES / key).glob(f"{key}-*.png")),
                             sorted(PNG_SIZES))

    def test_windows_icons_carry_every_frame(self):
        for key, _ in table_rows():
            with self.subTest(key=key):
                data = (GAMES / key / f"{key}.ico").read_bytes()
                self.assertEqual(struct.unpack_from("<HHH", data), (0, 1, len(ICO_SIZES)))
                previous_end = 6 + 16 * len(ICO_SIZES)
                for index, size in enumerate(ICO_SIZES):
                    w, h, colours, _, planes, bits, length, offset = struct.unpack_from(
                        "<BBBBHHII", data, 6 + index * 16)
                    self.assertEqual((w or 256, h or 256, colours, planes, bits), (size, size, 0, 1, 32))
                    self.assertEqual(offset, previous_end)
                    frame = data[offset:offset + length]
                    png = GAMES / key / f"{key}-{size}.png"
                    if png.exists():
                        self.assertEqual(frame, png.read_bytes())
                    else:
                        decode_png(self, frame, size)
                    previous_end = offset + length
                self.assertEqual(previous_end, len(data))

    def test_macos_icons_include_retina_representations(self):
        for key, _ in table_rows():
            with self.subTest(key=key):
                data = (GAMES / key / f"{key}.icns").read_bytes()
                self.assertEqual(struct.unpack_from(">4sI", data), (b"icns", len(data)))
                expected = dict(ICNS_SIZES)
                offset = 8
                while offset < len(data):
                    kind, length = struct.unpack_from(">4sI", data, offset)
                    size = expected.pop(kind)
                    frame = data[offset + 8:offset + length]
                    png = GAMES / key / f"{key}-{size}.png"
                    if png.exists():
                        self.assertEqual(frame, png.read_bytes())
                    else:
                        decode_png(self, frame, size)
                    offset += length
                self.assertFalse(expected)
                self.assertEqual(offset, len(data))

    def test_linux_launcher_templates_match_their_icons(self):
        for key, _ in table_rows():
            with self.subTest(key=key):
                text = (GAMES / key / f"fntech3-{key}.desktop").read_text(encoding="utf-8")
                lines = text.splitlines()
                self.assertEqual(lines[0], "[Desktop Entry]")
                entry = dict(line.split("=", 1) for line in lines[1:] if line)
                self.assertEqual(entry["Type"], "Application")
                self.assertEqual(entry["Exec"], f"fntech3 +set com_gameProfile {key}")
                self.assertEqual(entry["Icon"], f"fntech3-{key}")
                # SDL and the X11 backend advertise this id (ApplicationId()).
                self.assertEqual(entry["StartupWMClass"], f"fntech3-{key}")
                self.assertTrue(entry["Name"])
                self.assertTrue(entry["Categories"].endswith(";"))

    def test_generated_sources_match_the_committed_frames(self):
        for path in (TABLE, DATA, RESOURCES):
            self.assertIn(GENERATED, path.read_text(encoding="utf-8").splitlines()[0])
        rows = table_rows()
        data = DATA.read_text(encoding="utf-8")
        arrays = {name: bytes(int(v) for v in body.replace("\n", "").split(",") if v)
                  for name, body in re.findall(r"const unsigned char (k\w+)\[\d+\] = \{\n(.*?)\n\};", data, re.S)}
        images = re.findall(r'\{"([a-z0-9-]+)", (\d+), (k\w+), sizeof\(\3\)\},', data)
        self.assertEqual(len(images), len(rows) * len(EMBEDDED_SIZES))
        for key, size, name in images:
            with self.subTest(key=key, size=size):
                self.assertEqual(arrays[name], (GAMES / key / f"{key}-{size}.png").read_bytes())
        self.assertEqual({(key, int(size)) for key, size, _ in images},
                         {(key, size) for key, _ in rows for size in EMBEDDED_SIZES})
        script = RESOURCES.read_text(encoding="utf-8")
        mingw = script.split("#else")[1]
        msvc = script.split("#else")[0]
        for key, resource in rows:
            self.assertIn(f'{resource} ICON DISCARDABLE "../../assets/icons/games/{key}/{key}.ico"', msvc)
            self.assertIn(f'{resource} ICON DISCARDABLE "assets/icons/games/{key}/{key}.ico"', mingw)
        client = (ROOT / "code" / "win32" / "win_client_resource.rc").read_text(encoding="utf-8")
        self.assertIn('#include "win_resource.rc"', client)
        self.assertIn('#include "win_game_icons.rc"', client)

    def test_builds_link_icons_into_both_windows_executables(self):
        meson = (ROOT / "meson.build").read_text(encoding="utf-8")
        self.assertIn("client_resource_src = win_client_resource", meson)
        self.assertIn("server_resource_src = win_client_resource", meson)
        self.assertIn("client_resource_src = ['code/platform/game_icon_data.cpp']", meson)
        self.assertIn("q3_platform_src + client_resource_src + q3_ui_src", meson)
        self.assertIn("q3_platform_src + server_resource_src + qcommon_src", meson)
        self.assertIn("rename: 'fntech3-' + game_icon + '.png'", meson)
        cmake = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
        self.assertIn("SET(Q3_CLIENT_RESOURCES code/win32/win_client_resource.rc)", cmake)
        self.assertIn("SET(Q3_SERVER_RESOURCES code/win32/win_client_resource.rc)", cmake)
        self.assertIn("SET(Q3_CLIENT_RESOURCES code/platform/game_icon_data.cpp)", cmake)
        make = (ROOT / "Makefile").read_text(encoding="utf-8")
        self.assertIn("$(B)/client/win_client_resource.o", make)
        self.assertIn("$(B)/client/game_icon_data.o", make)


if __name__ == "__main__":
    unittest.main()
